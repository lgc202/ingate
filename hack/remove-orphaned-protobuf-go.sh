#!/usr/bin/env bash

set -Eeuo pipefail

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
readonly repo_root
readonly generated_marker='^// Code generated by protoc-gen-go(-grpc|-http)?[.] DO NOT EDIT[.]$'

input_roots=()
while IFS= read -r input_root; do
  if [[ -z "$input_root" || "$input_root" == /* || "/$input_root/" == */../* || ! -d "$repo_root/$input_root" ]]; then
    echo "invalid protobuf input root in buf.gen.yaml: $input_root" >&2
    exit 1
  fi
  input_roots+=("$input_root")
done < <(sed -n 's/^[[:space:]]*- directory: //p' "$repo_root/buf.gen.yaml")
readonly -a input_roots
if (( ${#input_roots[@]} == 0 )); then
  echo "buf.gen.yaml does not define a protobuf input root" >&2
  exit 1
fi

for input_root in "${input_roots[@]}"; do
  while IFS= read -r -d '' generated_file; do
    if [[ ! "$(sed -n '1p' "$generated_file")" =~ $generated_marker ]]; then
      continue
    fi

    source_file="$(sed -n 's#^// source: ##p' "$generated_file" | head -n 1)"
    if [[ -z "$source_file" || "$source_file" != *.proto || "$source_file" == /* || "/$source_file/" == */../* ]]; then
      echo "invalid protobuf source metadata in $generated_file" >&2
      exit 1
    fi
    if [[ ! -f "$repo_root/$input_root/$source_file" ]]; then
      printf 'remove orphaned protobuf Go file: %s\n' "${generated_file#"$repo_root/"}"
      rm -- "$generated_file"
    fi
  done < <(find "$repo_root/$input_root" -type f -name '*.pb.go' -print0)
done
